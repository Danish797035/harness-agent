// Build number on the about page: short hash of the current commit; write dev when there is no git (such
// as compiling from a source package)
val gitHash: String = runCatching {
    providers.exec { commandLine("git", "rev-parse", "--short=7", "HEAD") }.standardOutput.asText.get().trim()
}.getOrNull()?.takeIf { it.isNotEmpty() } ?: "dev"

android {
    namespace = "com.meenai.mina"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.danish.harnessagent"
        minSdk = 30
        targetSdk = 35
        val runNumber = (System.getenv("GITHUB_RUN_NUMBER")?.toIntOrNull()
            ?: (project.findProperty("versionCode") as? String)?.toIntOrNull()
            ?: 49)
        versionCode = runNumber
        versionName = "0.1.63"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        buildConfigField("String", "GIT_HASH", "\"$gitHash\"")
        // The Beta mark after the version number on the About page; change it to false when the official
        // version is released
        buildConfigField("boolean", "BETA", "true")
    }

    // The sandbox program only has the arm64 version (jniLibs/arm64-v8a); the APK is not limited to ABI.
    // Other devices will be installed as usual and "This device does not support sandboxing" will be
    // displayed. The sandbox program must be executed directly from nativeLibraryDir, and the disk must
    // be retrieved during installation.
    packaging { jniLibs { useLegacyPackaging = true } }

    // The release packages (perf, release) are released according to the architecture: in addition to
    // the full architecture package, there is also a small package with only the arm64-v8a native
    // library. The codes, resources, version numbers, and signatures of the two packages are the same,
    // except for other structures under lib/; each is a complete APK, not a split package installed
    // together. Products: app-universal-<type>.apk, app-arm64-v8a-<type>.apk. Splitting takes effect for all
    // build types, so it is only turned on when the perf/release package is to be produced in this
    // build. When the debug package is built separately, the product is still app-debug.apk.
    splits {
        abi {
            isEnable = gradle.startParameter.taskNames.any { Regex("(?i)(perf|release)").containsMatchIn(it) }
            reset()
            include("arm64-v8a")
            isUniversalApk = true
        }
    }
    // The built-in running environment (generated by assets/runtime/rootfs.tar.xz,
    // tools/sandbox/build-runtime.py) is already xz, no need to press it again.
    androidResources { noCompress += "xz" }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    // The evaluation task set (warehouse root directory eval/tasks) is entered into the assets of the
    // test package, and the real machine evaluation runner reads the questions from there.
    sourceSets.getByName("androidTest").assets.srcDir(rootProject.file("eval/tasks"))

    // GitHub Actions sets an env var for a secret that does not exist to the
    // empty string, so blank must count as "not set": an empty keyAlias or
    // storePassword otherwise fails the release build with "key  not found".
    fun envOr(fallback: String, vararg names: String): String =
        names.mapNotNull { System.getenv(it)?.takeIf(String::isNotBlank) }.firstOrNull() ?: fallback

    signingConfigs {
        // minSdk 30 se AGP v1 (JAR) signing band kar deta hai; kuch devices archive se
        // sirf v1 signatures padh paate hain, isliye update pre-check ke liye v1 on rakho.
        getByName("debug") {
            enableV1Signing = true
            storeFile = file(envOr("${System.getProperty("user.home")}/.android/debug.keystore", "DEBUG_KEYSTORE_FILE"))
            storePassword = envOr("android", "SIGNING_STORE_PASSWORD")
            keyAlias = envOr("androiddebugkey", "SIGNING_KEY_ALIAS")
            keyPassword = envOr("android", "SIGNING_KEY_PASSWORD")
        }
        // Release builds must not be debuggable. By default they reuse the same
        // keystore as the debug build so existing installs can still upgrade;
        // CI can point RELEASE_KEYSTORE_FILE at a dedicated release keystore.
        create("release") {
            enableV1Signing = true
            storeFile = file(envOr("${System.getProperty("user.home")}/.android/debug.keystore", "RELEASE_KEYSTORE_FILE"))
            storePassword = envOr("android", "RELEASE_STORE_PASSWORD", "SIGNING_STORE_PASSWORD")
            keyAlias = envOr("androiddebugkey", "RELEASE_KEY_ALIAS", "SIGNING_KEY_ALIAS")
            keyPassword = envOr("android", "RELEASE_KEY_PASSWORD", "SIGNING_KEY_PASSWORD")
        }
    }

    buildTypes {
        // Install side by side during real machine acceptance, retaining the release version and user
        // data; the default build identification remains unchanged.
        if (providers.gradleProperty("devInstall").isPresent) getByName("debug") {
            applicationIdSuffix = ".dev"
            resValue("string", "app_name", "Harness Agent Dev")
        }
        getByName("release") {
            signingConfig = signingConfigs.getByName("release")
            // R8 needs keep rules for kotlinx.serialization, reflection and the
            // JS bridges; enable shrinking only after a device test of the
            // minified build.
            isMinifyEnabled = false
            isShrinkResources = false
        }
        // The package used to check the fluency: it is not debuggable like the release version (the
        // debugging package is not pre-compiled, the interface is several times slower, and the feel
        // does not count). Using native debugging signatures can directly overwrite the debugging
        // package and retain data; it can be sampled by performance tools../gradlew:app:assemblePerf
        create("perf") {
            initWith(getByName("release"))
            signingConfig = signingConfigs.getByName("debug")
            isProfileable = true
            matchingFallbacks += "release"
        }
    }

    buildFeatures {
        compose = true
        aidl = true
        buildConfig = true
    }

    testOptions {
        unitTests.isReturnDefaultValues = true
    }
}

