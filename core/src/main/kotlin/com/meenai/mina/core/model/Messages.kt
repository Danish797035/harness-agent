package com.meenai.mina.core.model

import com.meenai.mina.core.observation.ReadTag
import kotlinx.serialization.Serializable

@Serializable
sealed interface Part {
    @Serializable
    data class Text(val text: String) : Part
    /**
     * [width]/[height]: The encoded pixel size, 0 means unknown (only used for token estimation).
     * [screenshotId]: This picture is from which screen reading time (you can use view_past_screens to
     * review it); if it is not a screen picture (read image file), it is null.
     */
    @Serializable data class Image(
        val pngBase64: String,
        val mime: String = "image/png",
        val width: Int = 0,
        val height: Int = 0,
        val screenshotId: Int? = null,
    ) : Part
    /**
     * [opaque]: adapter-private data that the SAME adapter must send back unchanged when this call is
     * replayed; other adapters ignore it.
     */
    @Serializable data class ToolCall(val id: String, val name: String, val argsJson: String, val opaque: String? = null) : Part
    /**
     * [reads]: observations read in this result and recorded in the evidence ledger (ID and shape);
     * used only internally by Mina (pruning decides how to shorten by shape and points back to ID), not
     * sent to the provider.
     */
    @Serializable data class ToolResult(val callId: String, val content: String, val isError: Boolean, val reads: List<ReadTag> = emptyList()) : Part
    /**
     * [opaque]: Like [ToolCall.opaque], it is private to the adapter. Note where this thought comes from
     * (for example, its address and fields are received in the compatible interface). During playback,
     * only the adapter that recognizes it will use it; other adapters will not read it. Old history and
     * those that do not need to be replayed are null.
     */
    @Serializable data class Thinking(val text: String, val opaque: String? = null) : Part
}

@Serializable
enum class Role { System, User, Assistant, Tool }

/** Who wrote the message: [User] is said by the user himself (original words of the task, words added during the task and photos), [Mina] is generated by Mina (notes, context, tool round-trip). */
@Serializable
enum class Author { User, Mina }

/**
 * [author] Must be specified (no default value): If the user's words or photos are placed in the newly
 * added place, they will not be cut off as Mina's notes. It is only used internally by Mina (to protect
 * users during compression) and will not be sent to service providers.
 */
@Serializable
data class Message(val role: Role, val parts: List<Part>, val author: Author)

data class ToolSpec(val name: String, val description: String, val parametersJsonSchema: String)

enum class StopReason { EndTurn, ToolUse, MaxTokens, Other }

/**
 * [inputTokens] is the total input token (including cache hit part, OpenAI prompt_tokens caliber).
 * [outputTokens] includes thinking; [reasoningTokens] is the thinking token reported separately by the
 * service provider (those not reported separately are 0, such as Anthropic).
 */
data class Usage(val inputTokens: Int, val outputTokens: Int, val cachedInputTokens: Int = 0, val reasoningTokens: Int = 0)

data class ModelReply(val parts: List<Part>, val stopReason: StopReason, val usage: Usage?)
